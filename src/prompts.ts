import type { Section } from "./types";

const sectionDescription = (sections: Section[]): string =>
  sections
    .map((section) => {
      const description = section.description
        ? ` — ${section.description}`
        : "";

      return `${section.id}: ${section.name}${description}`;
    })
    .join("\n");

export const extractionPrompt = (text: string): string => `
Ты извлекаешь из расшифровки строительного видео реальные пары
«вопрос зрителя — ответ автора».

ГЛАВНЫЙ ПРИНЦИП:
Извлекай только пары, которые действительно присутствуют в тексте.
Не пытайся заполнить FAQ любой ценой.
Лучше вернуть меньше достоверных пар, чем много сомнительных.

ОСОБЕННОСТИ РАСШИФРОВКИ:
- Переносы строк могут быть случайными.
- Символы >> могут быть артефактами.
- Возможны ошибки распознавания речи, повторы и незаконченные фразы.
- Не считай каждую новую строку отдельной репликой.
- Не исправляй исходные слова и не дополняй обрезанные фразы.

КАК ОПРЕДЕЛЯТЬ ВОПРОС:
1. question — реальный вопрос зрителя или явно заданный вопрос, на который
   автор отвечает в расшифровке.
2. Обычно вопрос заканчивается знаком ? или ？.
3. Сам по себе вопросительный знак не доказывает, что это вопрос зрителя.
4. Не превращай риторические вопросы и продолжения рассуждений автора в FAQ.
5. Не создавай вопросы из утверждений, советов, выводов и описаний.
6. Не превращай фразы «то есть...», «первое, нормативно...», «можно найти
   области применения...» и подобные рассуждения автора в вопросы.
7. Не выдумывай отсутствующий вопрос на основании ответа или темы разговора.
8. Не включай вступление автора в question.
9. Не включай в question ответ автора, который идёт после вопросительного знака.
10. Не объединяй несколько разных вопросов в один.
11. Если граница вопроса неясна или он обрезан, пропусти пару.

КАК ОПРЕДЕЛЯТЬ ОТВЕТ:
12. answer — дословный фрагмент ответа автора именно на этот вопрос.
13. Ответ должен находиться после вопроса.
14. Не считай ответом следующий вопрос, приветствие, шутку или переход к теме.
15. Между вопросом и ответом не должно быть другого вопроса, если связь
    с первым вопросом нельзя установить однозначно.
16. Не связывай вопрос с ответом только потому, что они относятся к одной теме.
17. Не используй один ответ для разных вопросов без явных оснований.
18. Если автор не ответил по существу, не создавай пару.
19. Не добавляй технические сведения из собственных знаний.

ДОСЛОВНОСТЬ:
20. question и answer должны быть дословными фрагментами исходного текста.
21. Сохраняй слова, порядок, пунктуацию и ошибки распознавания.
22. Не пересказывай, не сокращай и не редактируй.
23. Не соединяй разрозненные части текста в новую формулировку.
24. context — необязательный дословный фрагмент исходного текста, помогающий
    понять вопрос. Если его нет, верни пустую строку.

ПРИОРИТЕТ КАЧЕСТВА:
25. Возвращай только пары с высокой уверенностью в границах вопроса и ответа.
26. Не нужно набирать определённое количество пар.
27. Не извлекай отдельную пару из каждого вопросительного знака.
28. Не создавай несколько вариантов одной пары.
29. Если в тексте нет достоверных пар, верни пустой массив.

ПРОВЕРКА ПЕРЕД ВОЗВРАТОМ:
- question дословно присутствует в исходном тексте;
- question заканчивается вопросительным знаком;
- question действительно является вопросом, а не рассуждением автора;
- в question не включён текст ответа;
- answer дословно присутствует в исходном тексте и расположен после вопроса;
- answer действительно отвечает на question;
- пара не дублирует другую пару;
- для создания пары не потребовались догадки.

Если хотя бы один пункт вызывает сомнение, пропусти пару.

Верни только JSON:
{
  "items": [
    {
      "question": "Дословный вопрос из исходного текста?",
      "answer": "Дословный ответ автора",
      "context": "Дословный контекст или пустая строка"
    }
  ]
}
Если пар нет: {"items":[]}

ИСХОДНЫЙ ТЕКСТ:
<<<TRANSCRIPT
${text}
TRANSCRIPT
>>>`;

export const enrichmentPrompt = (
  qa: { question: string; answer: string; context: string },
  sections: Section[],
  existingTags: string[],
): string => `
Ты классифицируешь уже извлечённую пару FAQ о строительстве.

ВОПРОС ИЗ РАСШИФРОВКИ:
<<<QUESTION
${qa.question}
QUESTION
>>>

ДОСЛОВНЫЙ ОТВЕТ АВТОРА:
<<<AUTHOR_ANSWER
${qa.answer}
AUTHOR_ANSWER
>>>

КОНТЕКСТ:
<<<CONTEXT
${qa.context || "(контекст отсутствует)"}
CONTEXT
>>>

ДОСТУПНЫЕ РАЗДЕЛЫ:
${sectionDescription(sections)}

СУЩЕСТВУЮЩИЕ ТЕГИ:
${existingTags.join(", ") || "(пока нет)"}

РАЗДЕЛЫ И ТЕГИ:
1. Выбирай только существующие ID разделов из списка.
2. Один вопрос может относиться к нескольким разделам.
3. Используй короткие русскоязычные теги.
4. Переиспользуй подходящие существующие теги.
5. Не создавай новые разделы и не используй целые предложения в качестве тегов.
6. Не выбирай раздел только по одному совпавшему слову.

needsContext:
7. true, если вопрос нельзя надёжно понять без отсутствующего контекста.
8. Не ставь true только из-за краткости самодостаточного вопроса.
9. Не выдумывай сведения о конкретном доме, проекте или конструкции.

aiAnswer:
10. Это самостоятельный ответ ИИ на вопрос, отдельно от слов автора.
11. Не выдавай мнение ИИ за слова автора.
12. Отвечай по существу, если надёжный общий ответ возможен.
13. Не выдумывай размеры, цены, характеристики материалов, нормативы,
    расчёты, условия проекта или цитаты из нормативных документов.
14. Не утверждай конкретные технические параметры без достаточных данных.
15. Если ответ зависит от проекта, региона, конструкции или неизвестных условий,
    явно обозначь эту зависимость и укажи, какие данные нужны.
16. Не выдавай предположение за установленный технический факт.
17. Если надёжно ответить нельзя, верни пустую строку.
18. Если needsContext=true, aiAnswer должен быть пустой строкой.

СРАВНЕНИЕ:
19. Сравнивай aiAnswer только с дословным ответом автора.
20. Сравнивай смысл ответов, а не их истинность.
21. Если авторский ответ не отвечает на вопрос по существу, используй
    статус not_comparable.
22. Если aiAnswer пустой или needsContext=true, используй not_comparable.
23. agree — основные выводы совпадают, существенных противоречий нет.
24. partially_agree — основная мысль совпадает, но есть важные отличия
    или неполнота.
25. disagree — есть прямое существенное противоречие по вопросу.
26. Не ставь disagree только потому, что один ответ подробнее другого.
27. Совместимые дополнительные сведения сами по себе не являются противоречием.
28. agreementPercent — условная оценка смыслового совпадения, не вероятность
    истинности:
    - agree: 80–100;
    - partially_agree: 30–79;
    - disagree: 0–29;
    - not_comparable: 0.
29. summary — краткое объяснение сравнения. Для not_comparable объясни причину.

Верни только JSON:
{
  "sections": [],
  "tags": [],
  "needsContext": false,
  "aiAnswer": "",
  "aiComparison": {
    "status": "not_comparable",
    "agreementPercent": 0,
    "summary": "Краткая причина"
  }
}
`;
