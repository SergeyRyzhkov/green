import type { Section } from "./types.js";

const jsonOnly = `Верни только корректный JSON без Markdown и пояснений.`;

export const qaExtractionPrompt = (text: string): string => `
Ты внимательно анализируешь расшифровку русскоязычного строительного видео и извлекаешь FAQ.

Нужно вернуть пары «ВОПРОС ЗРИТЕЛЯ — ОТВЕТ АВТОРА», которые подтверждаются текстом.

КРИТИЧЕСКИ ВАЖНЫЕ ПРАВИЛА

1. Что считать вопросом:
- Это содержательный вопрос зрителя из комментария, письма, чата или устного обращения.
- Вопрос может быть сформулирован без знака вопроса: «Подскажите, как…», «Интересует…», «Расскажите про…», «Есть ли смысл…».
- Сохраняй все относящиеся к одному вопросу условия: материал, размеры, регион, конструкцию, ограничения и дополнительные уточнения.
- Если несколько вопросов относятся к одному и тому же конкретному сценарию, можно объединить их в один вопрос, если это не делает его чрезмерно длинным.
- Независимые вопросы о разных конструкциях или проблемах должны быть отдельными парами.

2. Что НЕ считать вопросом:
- Реплики самого автора, риторические вопросы автора и вопросы, которые автор задаёт аудитории.
- Ответ автора, ошибочно оформленный как вопрос.
- Обрывки «А где ещё?», «А если так?», «Как лучше это сделать?» без достаточного контекста в самой цитате.
- Названия тем, утверждения, просьбы «ответьте на вопрос» без содержательного вопроса.
- Повтор вопроса, уже включённого в более полную формулировку.

3. Цитата вопроса:
- questionQuote должна быть дословной НЕПРЕРЫВНОЙ цитатой из расшифровки.
- Не исправляй распознавание речи, орфографию, грамматику, числа или пунктуацию.
- Не добавляй отсутствующие слова и не склеивай удалённые части текста.
- Не включай в вопрос ответ автора.
- Если невозможно уверенно определить границы вопроса, пропусти пару.

4. Цитата ответа:
- answerQuote должна быть дословной НЕПРЕРЫВНОЙ цитатой из расшифровки и содержать именно ответ автора на этот вопрос.
- Включай несколько следующих предложений, если они раскрывают тот же ответ, его условия, исключения или вывод.
- Не включай постороннее обсуждение другой темы.
- Не сочиняй ответ на основании общих знаний.
- Автор может ответить встречным вопросом, например «А какие проблемы вам видятся…?». Это само по себе не является ответом. Если далее в этом фрагменте нет содержательного ответа, пару не возвращай.
- Вопрос должен предшествовать ответу в тексте. Не переставляй цитаты местами.
- Не склеивай предложения, между которыми есть существенный посторонний фрагмент.

5. Соответствие вопроса и ответа:
- Не связывай вопрос и ответ только потому, что они находятся рядом.
- Ответ должен прямо отвечать на вопрос или явно продолжать обсуждение именно этого вопроса.
- Если в расшифровке есть вопрос, но ответа в данном фрагменте нет, не возвращай его.
- Если ответ относится к вопросу из предыдущего фрагмента, не придумывай недостающую цитату вопроса.

6. Приоритет качества:
- Лучше вернуть меньше надёжных пар, чем много ложных.
- Возвращай не больше 12 пар из одного фрагмента.
- Цитаты могут содержать ошибки ASR; сохраняй их как есть.

Формат:
{
  "pairs": [
    { "questionQuote": "дословная цитата вопроса", "answerQuote": "дословная цитата ответа" }
  ]
}
Если пар нет: {"pairs": []}

${jsonOnly}

РАСШИФРОВКА:
<<<TRANSCRIPT>>>
${text}
<<<END TRANSCRIPT>>>
`;

export const enrichmentPrompt = (
  question: string,
  authorAnswer: string,
  sections: Section[],
): string => `
Ты независимый технический помощник, анализирующий FAQ по строительству.

Вопрос зрителя:
${question}

Дословный ответ автора:
${authorAnswer}

Доступные разделы:
${JSON.stringify(sections.map(({ id, name, description }) => ({ id, name, description })))}

Верни JSON с полями:
- sections: массив ID подходящих разделов из предоставленного списка; обычно 1–3. Не выдумывай ID.
- aiAnswer: независимый ответ на вопрос по существу на русском языке. Не выдавай предположения за факты. Укажи существенные ограничения и когда нужны расчёты специалиста. Если нельзя ответить надёжно, верни null.
- comparison: null, если aiAnswer равен null; иначе объект {status, agreementPercent, summary}.
  status: agree | partially_agree | disagree | not_comparable.
  agreementPercent: целое число 0–100, оценивающее совпадение по техническому смыслу, а не совпадение формулировок.
  summary: кратко объясни, в чём совпадают или расходятся ответы. Не считай ответ автора верным только потому, что он авторский.

Не переписывай и не исправляй авторский ответ: он хранится отдельно и остаётся исходным.

${jsonOnly}
`;
