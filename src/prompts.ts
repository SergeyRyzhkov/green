const jsonOnly = `
Верни только корректный JSON.
Не используй Markdown, комментарии или текст вне JSON.
`;

export const qaExtractionPrompt = (text: string): string => `
Ты извлекаешь FAQ из расшифровки русскоязычного строительного видео.

Твоя задача — найти вопросы зрителей и соответствующие ответы автора.
Возвращай сразу связанные пары «вопрос — ответ».

ОСНОВНЫЕ ПРАВИЛА

1. ВОПРОС

- Найди реальный вопрос зрителя, заданный в комментарии,
  сообщении, письме или устно.
- Сохраняй вопрос целиком, включая все предложения, уточнения,
  исходные условия, перечисления и пояснения, которые относятся
  к одному вопросу.
- Не обрезай длинный вопрос до первого вопросительного знака.
- Если вопрос начинается словами «Здравствуйте», «Подскажите»,
  «У меня такая ситуация» или содержит описание объекта,
  сохрани значимую часть этого описания.
- Если вопрос сформулирован неявно, но автор явно отвечает на
  обращение зрителя, можно включить его только тогда, когда
  содержание вопроса понятно из исходного текста.
- questionQuote должен быть дословной непрерывной цитатой
  из расшифровки. Не исправляй слова, ошибки распознавания,
  грамматику и пунктуацию.
- Не придумывай недостающие части вопроса.

2. ОТВЕТ

- answerQuote — дословный непрерывный фрагмент расшифровки,
  содержащий ответ автора именно на этот вопрос.
- Начинай с ответа по существу, если он явно присутствует.
- Включай следующие предложения, если они продолжают ответ,
  уточняют условия, ограничения, исключения или вывод.
- Не обрывай ответ после первой фразы, если автор продолжает
  объяснять ту же тему.
- Не включай постороннее обсуждение других вопросов.
- Не включай собственные знания, пояснения или пересказ.
- Если автор не ответил на вопрос в данном фрагменте,
  не возвращай эту пару.
- Если автор возвращается к вопросу после короткого отступления,
  выбирай только непрерывную цитату, которая действительно
  содержится в расшифровке. Не склеивай удалённые предложения.

3. НЕ СОЗДАВАЙ ЛОЖНЫЕ ВОПРОСЫ

Не возвращай как отдельные вопросы:
- «Прошу ответить на мой вопрос», «что скажете?», «понятно?»,
  если содержательный вопрос не указан;
- продолжения вроде «а если так?», «сравниваем со свайным»,
  если без предыдущего контекста они не имеют самостоятельного смысла;
- риторические вопросы автора;
- вопросы, которые автор задаёт аудитории;
- названия тем, предположения и отдельные реплики без запроса;
- повторный вопрос, если он уже входит в более полный вопрос.

4. НЕ РАЗБИВАЙ ОДИН ВОПРОС НА НЕСКОЛЬКО

Если зритель сначала описывает ситуацию, затем задаёт несколько
связанных уточнений и в конце формулирует основной вопрос,
считай это одним вопросом, если все части относятся к одной
строительной ситуации и одному ответу.

Если в одном сообщении действительно заданы два независимых
вопроса, на которые автор даёт разные ответы, верни две пары.

5. ТОЧНОСТЬ

- Не выдумывай вопрос ради увеличения количества FAQ.
- Не считай вопрос и ответ связанными только потому, что они
  находятся рядом в тексте.
- Не исправляй ошибки расшифровки.
- Не нормализуй исходные цитаты.
- Если сомневаешься, лучше пропусти пару.
- Обе цитаты должны быть непрерывными фрагментами текста
  из переданной расшифровки.
- Вопрос должен идти раньше своего ответа в исходном фрагменте.

ФОРМАТ ОТВЕТА

{
  "pairs": [
    {
      "questionQuote": "полная дословная цитата вопроса",
      "answerQuote": "полная дословная цитата ответа автора"
    }
  ]
}

Если подходящих пар нет, верни:
{
  "pairs": []
}

${jsonOnly}

РАСШИФРОВКА:
${text}
`;

export const enrichmentPrompt = (
  question: string,
  authorAnswer: string,
  sections: Section[],
): string => `
Ты анализируешь FAQ по строительству.

ВОПРОС ЗРИТЕЛЯ:
${question}

ДОСЛОВНЫЙ ОТВЕТ АВТОРА:
${authorAnswer}

ДОСТУПНЫЕ РАЗДЕЛЫ:
${JSON.stringify(
  sections.map(({ id, name, description }) => ({
    id,
    name,
    description,
  })),
  null,
  2,
)}

ЗАДАЧИ

1. Выбери все подходящие разделы по их id.
Один FAQ может относиться к нескольким разделам.
Используй только предоставленные id.
Если подходящих разделов нет, верни [].

2. Дай самостоятельный ответ ИИ на вопрос.
Не выдавай предположения за факты.
Учитывай условия и ограничения, указанные автором, но не считай
его утверждения автоматически правильными.
Если надёжно ответить нельзя, верни null.
Не подменяй самостоятельный ответ простым копированием автора.

3. Сравни ответ ИИ с ответом автора.
- agree: по существу совпадают;
- partially_agree: совпадают частично или есть существенные уточнения;
- disagree: есть существенное противоречие;
- not_comparable: сравнить невозможно.

agreementPercent — ориентировочная степень совпадения от 0 до 100.
summary — короткое объяснение сравнения.
Если aiAnswer равен null, comparison должен быть null.
Не делай вывод о согласии только потому, что ответы посвящены одной теме.

ФОРМАТ:
{
  "sections": ["section-id"],
  "aiAnswer": "самостоятельный ответ или null",
  "comparison": {
    "status": "agree",
    "agreementPercent": 100,
    "summary": "Краткое объяснение"
  }
}

${jsonOnly}
`;
